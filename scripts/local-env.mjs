// Writes .env.development.local for local development from the running local
// Supabase stack (`supabase status`). Those keys are the CLI's local demo keys,
// not secrets of any real project. Server secrets (CRON_SECRET, RATE_LIMIT_SALT)
// and the local test owner password are generated once and kept on re-runs.
//
// Stripe and Resend keys are NOT written here: put your own test keys in
// .env.local (see .env.example).

import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const file = join(root, ".env.development.local");

const status = JSON.parse(
  execFileSync("npx", ["supabase", "status", "-o", "json"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })
);

const existing = {};
if (existsSync(file)) {
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) existing[m[1]] = m[2];
  }
}
const keep = (name, make) => existing[name] || make();
const secret = () => randomBytes(32).toString("base64url");

const env = {
  NEXT_PUBLIC_SITE_URL: "http://localhost:3000",
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
  SUPABASE_SECRET_KEY: status.SECRET_KEY,
  CRON_SECRET: keep("CRON_SECRET", secret),
  RATE_LIMIT_SALT: keep("RATE_LIMIT_SALT", secret),
  STATUS_LINK_SECRET: keep("STATUS_LINK_SECRET", secret),
  ALLOW_TEST_CLOCK: "1",
  DEV_OWNER_EMAIL: keep("DEV_OWNER_EMAIL", () => "owner@gourmand.test"),
  DEV_OWNER_PASSWORD: keep("DEV_OWNER_PASSWORD", () => `Gm-${randomBytes(12).toString("base64url")}`),
  // Local Mailpit catches Supabase Auth emails (password reset).
  LOCAL_MAILPIT_URL: status.MAILPIT_URL ?? status.INBUCKET_URL ?? "",
};

const body = [
  "# GENERATED by scripts/local-env.mjs for LOCAL development only.",
  "# Supabase values are the local CLI stack's demo keys. Re-run `npm run db:env`.",
  ...Object.entries(env).map(([k, v]) => `${k}=${v}`),
  "",
].join("\n");
writeFileSync(file, body, { mode: 0o600 });
console.log(`Wrote ${file} (Supabase at ${status.API_URL}).`);

// pg_cron calls the dev server's /api/cron every minute (from inside Docker
// the host machine is host.docker.internal). Ignored if the migration that
// adds private.set_app_cron_target hasn't run yet.
try {
  const sql = `select private.set_app_cron_target('http://host.docker.internal:3000/api/cron', '${env.CRON_SECRET}')`;
  execFileSync("npx", ["supabase", "db", "query", "--local", sql], { cwd: root, stdio: "ignore" });
  console.log("pg_cron → http://host.docker.internal:3000/api/cron every minute.");
} catch {
  console.log("Skipped pg_cron target (run migrations, then `npm run db:env`).");
}
