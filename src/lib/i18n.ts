export const dictionaries: Record<Locale, Dictionary> = { bg, en };

export function getDictionary(locale: Locale) {
  return dictionaries[locale];
}

// "350 г" → "350 g", "2 бр." → "2 pcs", "500 мл" → "500 ml" on English pages.
export function localizeWeight(weight: string, locale: Locale) {
  if (locale === "bg" || !weight) return weight;
  // `\b` doesn't work with Cyrillic, hence the explicit lookaheads.
  return weight
    .replace(/(\d)\s*гр?\.?(?![а-я])/g, "$1 g")
    .replace(/(\d)\s*мл\.?(?![а-я])/g, "$1 ml")
    .replace(/(\d)\s*кг\.?(?![а-я])/g, "$1 kg")
    .replace(/(\d+)\s*бр\.?(?![а-я])/g, (_, d: string) => `${d} ${d === "1" ? "pc" : "pcs"}`);
}

export function percentLabel(bps: number, locale: Locale) {
  const value = bps / 100;
  const text = Number.isInteger(value) ? String(value) : value.toFixed(1).replace(".", locale === "bg" ? "," : ".");
  return `${text}%`;
}
